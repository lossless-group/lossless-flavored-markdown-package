/**
 * The `lfm-tasks` script, run for real against a throwaway git repo.
 *
 * It is the one place in this package that touches the filesystem and git, so the
 * tests spawn the built file rather than importing anything: that also proves the
 * tsup entry and its shebang work.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const CLI = resolve(dirname(fileURLToPath(import.meta.url)), '../dist/cli/lfm-tasks.js');

function repo(t, files, { untracked = {} } = {}) {
  const dir = mkdtempSync(join(tmpdir(), 'lfm-tasks-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const write = (entries) => {
    for (const [path, body] of Object.entries(entries)) {
      mkdirSync(dirname(join(dir, path)), { recursive: true });
      writeFileSync(join(dir, path), body);
    }
  };
  write(files);
  execFileSync('git', ['init', '-q'], { cwd: dir });
  execFileSync('git', ['add', '.'], { cwd: dir });
  write(untracked);
  return dir;
}

const run = (cwd, ...args) => spawnSync(process.execPath, [CLI, ...args], { cwd, encoding: 'utf8' });

test('aggregates tracked files by assignee, linking to the true source line', (t) => {
  const dir = repo(t, {
    'plans/Launch.md': '---\ntitle: Launch\n---\n\n- [ ] @mpstaton Ship it #Docs 2026-11-15\n- [x] Done\n',
    'README.md': '- [ ] Unowned\n',
  });
  const { stdout, status } = run(dir);
  assert.equal(status, 0);
  assert.equal(
    stdout,
    [
      '# Tasks',
      '',
      '2 open tasks across 2 documents. Generated by `lfm-tasks`, so edit the linked documents rather than this file.',
      '',
      '## @mpstaton',
      '',
      '- [ ] @mpstaton Ship it #Docs 2026-11-15 ([plans/Launch.md:5](plans/Launch.md?plain=1#L5))',
      '',
      '## Unassigned',
      '',
      '- [ ] Unowned ([README.md:1](README.md?plain=1#L1))',
      '',
      '<details>',
      '<summary>Completed (1)</summary>',
      '',
      '- [x] Done ([plans/Launch.md:6](plans/Launch.md?plain=1#L6))',
      '',
      '</details>',
      '',
    ].join('\n'),
  );
});

test('frontmatter never becomes a section', (t) => {
  const dir = repo(t, { 'a.md': '---\ntitle: x\n---\n\n- [ ] One\n' });
  assert.match(run(dir, '--group-by', 'section').stdout, /## No Section/);
});

test('untracked files are ignored', (t) => {
  const dir = repo(t, { 'a.md': '- [ ] Tracked\n' }, { untracked: { 'b.md': '- [ ] Untracked\n' } });
  const { stdout } = run(dir);
  assert.match(stdout, /Tracked/);
  assert.doesNotMatch(stdout, /Untracked/);
});

test('regenerating reads past its own output and changes nothing', (t) => {
  const dir = repo(t, { 'a.md': '- [ ] One\n' });
  run(dir, '-o', 'TASKS.md');
  const first = readFileSync(join(dir, 'TASKS.md'), 'utf8');
  execFileSync('git', ['add', '.'], { cwd: dir });
  run(dir, '-o', 'TASKS.md');
  assert.equal(readFileSync(join(dir, 'TASKS.md'), 'utf8'), first);
  assert.match(first, /1 open task across 1 document\./);
});

test('links are relative to the output file', (t) => {
  const dir = repo(t, { 'plans/a b.md': '- [ ] One\n', 'docs/.keep': '' });
  run(dir, '-o', 'docs/TASKS.md');
  const out = readFileSync(join(dir, 'docs/TASKS.md'), 'utf8');
  assert.match(out, /\[plans\/a b\.md:1\]\(\.\.\/plans\/a%20b\.md\?plain=1#L1\)/);
});

test('paths and --exclude narrow what is read', (t) => {
  const dir = repo(t, {
    'plans/a.md': '- [ ] InPlans\n',
    'plans/old/b.md': '- [ ] InOld\n',
    'c.md': '- [ ] AtRoot\n',
  });
  const { stdout } = run(dir, 'plans', '--exclude', 'plans/old');
  assert.match(stdout, /InPlans/);
  assert.doesNotMatch(stdout, /InOld|AtRoot/);
});

test('--collaborators limits who counts', (t) => {
  const dir = repo(t, { 'a.md': '- [ ] @page rules\n- [ ] @mpstaton Real\n' });
  const { stdout } = run(dir, '--collaborators', 'mpstaton');
  assert.match(stdout, /## @mpstaton/);
  assert.doesNotMatch(stdout, /## @page/);
});

test('a repo with no tasks still produces a file', (t) => {
  const dir = repo(t, { 'a.md': 'Prose.\n' });
  const { stdout, status } = run(dir);
  assert.equal(status, 0);
  assert.match(stdout, /0 open tasks across 0 documents/);
});

test('fails clearly outside a git repo and on a bad option', (t) => {
  const dir = mkdtempSync(join(tmpdir(), 'lfm-tasks-'));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  const outside = run(dir);
  assert.equal(outside.status, 1);
  assert.match(outside.stderr, /git repository/);

  const inside = repo(t, { 'a.md': '- [ ] One\n' });
  const bad = run(inside, '--group-by', 'nope');
  assert.equal(bad.status, 1);
  assert.match(bad.stderr, /--group-by must be/);
});

test('a page reference becomes a link GitHub can follow', (t) => {
  const dir = repo(t, {
    'plans/a.md': [
      '- [ ] Exact [[specs/Page-Name.md]]',
      '- [ ] Section [[specs/Page-Name.md#Why Care|why]]',
      '- [ ] Bare [[Page-Name]]',
      '- [ ] Relative [[../specs/Page-Name.md]]',
      '- [ ] Missing [[nowhere/Gone.md]]',
      '- [ ] Ambiguous [[Twin]]',
      '',
    ].join('\n'),
    'specs/Page-Name.md': 'Prose.\n',
    'one/Twin.md': 'Prose.\n',
    'two/Twin.md': 'Prose.\n',
    'docs/.keep': '',
  });
  run(dir, 'plans', '-o', 'docs/TASKS.md');
  const out = readFileSync(join(dir, 'docs/TASKS.md'), 'utf8');
  assert.match(out, /Exact \[Page Name\]\(\.\.\/specs\/Page-Name\.md\) /);
  assert.match(out, /Section \[why\]\(\.\.\/specs\/Page-Name\.md#why-care\) /);
  assert.match(out, /Bare \[Page Name\]\(\.\.\/specs\/Page-Name\.md\) /);
  assert.match(out, /Relative \[Page Name\]\(\.\.\/specs\/Page-Name\.md\) /);
  assert.match(out, /Missing Gone \(/);
  assert.match(out, /Ambiguous Twin \(/);
  assert.doesNotMatch(out, /\[\[/);
  assert.equal(readFileSync(join(dir, 'plans/a.md'), 'utf8').includes('[[specs/Page-Name.md]]'), true);
});

test('changelog directories are skipped unless asked for', (t) => {
  const dir = repo(t, {
    'a.md': '- [ ] Current\n',
    'changelog/2026-01-01_01.md': '- [ ] OldEntry\n',
    'apps/x/changelog/2026-01-01_01.md': '- [ ] NestedEntry\n',
    'changelog.md': '- [ ] SingleFile\n',
  });
  const skipped = run(dir).stdout;
  assert.match(skipped, /Current/);
  assert.match(skipped, /SingleFile/);
  assert.doesNotMatch(skipped, /OldEntry|NestedEntry/);
  assert.match(run(dir, '--include-changelog').stdout, /OldEntry[\s\S]*|NestedEntry/);
  assert.match(run(dir, '--include-changelog').stdout, /NestedEntry/);
});

test('a page reference into a changelog still resolves', (t) => {
  const dir = repo(t, {
    'a.md': '- [ ] See [[changelog/Entry.md]]\n',
    'changelog/Entry.md': 'Prose.\n',
  });
  assert.match(run(dir).stdout, /\[Entry\]\(changelog\/Entry\.md\)/);
});

test('--staged reads the index, not the working tree', (t) => {
  const dir = repo(t, { 'a.md': '- [ ] Staged\n' });
  writeFileSync(join(dir, 'a.md'), '- [ ] Unstaged\n');
  const { stdout } = run(dir, '--staged');
  assert.match(stdout, /Staged/);
  assert.doesNotMatch(stdout, /Unstaged/);
});

/* The pre-commit hook, exercised by real commits. */

const hermetic = { ...process.env, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_SYSTEM: '/dev/null' };
const git = (cwd, ...args) =>
  execFileSync('git', ['-c', 'user.name=Test', '-c', 'user.email=test@example.com', ...args], {
    cwd,
    encoding: 'utf8',
    env: hermetic,
    stdio: ['ignore', 'pipe', 'pipe'],
  });
const installHook = (cwd) =>
  spawnSync(process.execPath, [CLI, '--install-hook'], { cwd, encoding: 'utf8', env: hermetic });
const committed = (cwd) => git(cwd, 'show', '--name-only', '--format=', 'HEAD').trim().split('\n');

function hooked(t, files = { 'README.md': 'Prose.\n' }) {
  const dir = repo(t, files);
  git(dir, 'commit', '-qm', 'start');
  assert.equal(installHook(dir).status, 0);
  return dir;
}

test('a commit touching context-v carries an updated TASKS.md', (t) => {
  const dir = hooked(t);
  mkdirSync(join(dir, 'context-v/plans'), { recursive: true });
  writeFileSync(join(dir, 'context-v/plans/Launch.md'), '- [ ] @mpstaton Ship\n');
  git(dir, 'add', '.');
  git(dir, 'commit', '-qm', 'plan');
  assert.deepEqual(committed(dir).sort(), ['TASKS.md', 'context-v/plans/Launch.md']);
  assert.match(git(dir, 'show', 'HEAD:TASKS.md'), /@mpstaton Ship/);
  assert.equal(git(dir, 'status', '--porcelain'), '', 'nothing left behind');
});

test('a nested context-v also triggers it', (t) => {
  const dir = hooked(t);
  mkdirSync(join(dir, 'apps/x/context-v'), { recursive: true });
  writeFileSync(join(dir, 'apps/x/context-v/Plan.md'), '- [ ] Nested\n');
  git(dir, 'add', '.');
  git(dir, 'commit', '-qm', 'plan');
  assert.ok(committed(dir).includes('TASKS.md'));
});

test('a commit elsewhere leaves TASKS.md alone', (t) => {
  const dir = hooked(t);
  writeFileSync(join(dir, 'README.md'), '- [ ] Not in context-v\n');
  git(dir, 'add', '.');
  git(dir, 'commit', '-qm', 'readme');
  assert.deepEqual(committed(dir), ['README.md']);
  assert.equal(existsSync(join(dir, 'TASKS.md')), false);
});

test('unstaged edits stay out of the committed TASKS.md', (t) => {
  const dir = hooked(t, { 'context-v/a.md': '- [ ] One\n' });
  writeFileSync(join(dir, 'context-v/a.md'), '- [ ] Two\n');
  git(dir, 'add', '.');
  writeFileSync(join(dir, 'context-v/a.md'), '- [ ] Unfinished thought\n');
  git(dir, 'commit', '-qm', 'two');
  const tasks = git(dir, 'show', 'HEAD:TASKS.md');
  assert.match(tasks, /Two/);
  assert.doesNotMatch(tasks, /Unfinished/);
});

test('deleting a context-v document updates the list', (t) => {
  const dir = hooked(t, { 'context-v/a.md': '- [ ] Gone soon\n', 'README.md': 'Prose.\n' });
  writeFileSync(join(dir, 'context-v/b.md'), '- [ ] Stays\n');
  git(dir, 'add', '.');
  git(dir, 'commit', '-qm', 'add');
  assert.match(git(dir, 'show', 'HEAD:TASKS.md'), /Gone soon/);
  git(dir, 'rm', '-q', 'context-v/a.md');
  git(dir, 'commit', '-qm', 'remove');
  assert.doesNotMatch(git(dir, 'show', 'HEAD:TASKS.md'), /Gone soon/);
});

test('git commit <path> works and carries the list', (t) => {
  const dir = hooked(t, { 'context-v/a.md': '- [ ] One\n', 'context-v/b.md': '- [ ] Two\n' });
  writeFileSync(join(dir, 'context-v/a.md'), '- [ ] One changed\n');
  git(dir, 'commit', '-qm', 'partial', 'context-v/a.md');
  assert.match(git(dir, 'show', 'HEAD:TASKS.md'), /One changed/);
  assert.equal(git(dir, 'status', '--porcelain'), '', 'nothing left behind');
});

test('a broken hook target warns and still commits', (t) => {
  const dir = hooked(t);
  const hookPath = git(dir, 'rev-parse', '--git-path', 'hooks/pre-commit').trim();
  const body = readFileSync(join(dir, hookPath), 'utf8');
  writeFileSync(join(dir, hookPath), body.replaceAll(CLI, '/nowhere/lfm-tasks.js'));
  mkdirSync(join(dir, 'context-v'));
  writeFileSync(join(dir, 'context-v/a.md'), '- [ ] One\n');
  git(dir, 'add', '.');
  const commit = spawnSync('git', ['-c', 'user.name=T', '-c', 'user.email=t@example.com', 'commit', '-m', 'x'], {
    cwd: dir,
    encoding: 'utf8',
    env: hermetic,
  });
  assert.equal(commit.status, 0);
  assert.match(commit.stderr, /could not update TASKS\.md/);
  assert.deepEqual(committed(dir), ['context-v/a.md']);
});

test('install refuses a hook it does not own, and reinstalls its own', (t) => {
  const dir = repo(t, { 'a.md': 'Prose.\n' });
  const hookPath = join(dir, git(dir, 'rev-parse', '--git-path', 'hooks/pre-commit').trim());
  mkdirSync(dirname(hookPath), { recursive: true });
  writeFileSync(hookPath, '#!/bin/sh\necho mine\n');
  const refused = installHook(dir);
  assert.equal(refused.status, 1);
  assert.match(refused.stderr, /isn't ours/);
  assert.equal(readFileSync(hookPath, 'utf8'), '#!/bin/sh\necho mine\n');

  rmSync(hookPath);
  assert.equal(installHook(dir).status, 0);
  assert.equal(installHook(dir).status, 0, 'its own hook can be replaced');
});

test('install refuses when core.hooksPath is set', (t) => {
  const dir = repo(t, { 'a.md': 'Prose.\n' });
  git(dir, 'config', 'core.hooksPath', 'shared-hooks');
  const refused = installHook(dir);
  assert.equal(refused.status, 1);
  assert.match(refused.stderr, /core\.hooksPath/);
  assert.equal(existsSync(join(dir, 'shared-hooks/pre-commit')), false);
});

test('the commit after a git commit <path> keeps TASKS.md', (t) => {
  const dir = hooked(t, { 'context-v/a.md': '- [ ] One\n', 'README.md': 'Prose.\n' });
  writeFileSync(join(dir, 'context-v/a.md'), '- [ ] One changed\n');
  git(dir, 'commit', '-qm', 'partial', 'context-v/a.md');
  writeFileSync(join(dir, 'README.md'), 'More prose.\n');
  git(dir, 'add', 'README.md');
  git(dir, 'commit', '-qm', 'next');
  assert.deepEqual(committed(dir), ['README.md']);
  assert.match(git(dir, 'show', 'HEAD:TASKS.md'), /One changed/);
});

test('git commit -a and --amend both carry the list', (t) => {
  const dir = hooked(t, { 'context-v/a.md': '- [ ] One\n' });
  writeFileSync(join(dir, 'context-v/a.md'), '- [ ] Via all\n');
  git(dir, 'commit', '-qam', 'all');
  assert.match(git(dir, 'show', 'HEAD:TASKS.md'), /Via all/);
  writeFileSync(join(dir, 'context-v/a.md'), '- [ ] Via amend\n');
  git(dir, 'add', '.');
  git(dir, 'commit', '-q', '--amend', '-m', 'amended');
  assert.match(git(dir, 'show', 'HEAD:TASKS.md'), /Via amend/);
  assert.equal(git(dir, 'status', '--porcelain'), '');
});

test('install writes nothing if either hook is not ours', (t) => {
  const dir = repo(t, { 'a.md': 'Prose.\n' });
  const hookOf = (name) => join(dir, git(dir, 'rev-parse', '--git-path', `hooks/${name}`).trim());
  mkdirSync(dirname(hookOf('post-commit')), { recursive: true });
  writeFileSync(hookOf('post-commit'), '#!/bin/sh\necho mine\n');
  rmSync(hookOf('pre-commit'), { force: true });
  assert.equal(installHook(dir).status, 1);
  assert.equal(existsSync(hookOf('pre-commit')), false);
});

test('the hook survives its pinned node going away', (t) => {
  const dir = hooked(t);
  const hookPath = join(dir, git(dir, 'rev-parse', '--git-path', 'hooks/pre-commit').trim());
  writeFileSync(hookPath, readFileSync(hookPath, 'utf8').replaceAll(process.execPath, '/nowhere/node'));
  mkdirSync(join(dir, 'context-v'));
  writeFileSync(join(dir, 'context-v/a.md'), '- [ ] One\n');
  git(dir, 'add', '.');
  git(dir, 'commit', '-qm', 'x');
  assert.ok(committed(dir).includes('TASKS.md'));
});
